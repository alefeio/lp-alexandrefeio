const BY_SLUG = new Map(FIRST_VALUE_LESSON_CATALOG.map((row) => [row.lessonSlug, row]));

export function firstValueLessonBySlug(slug: string): FirstValueLessonDefinition | undefined {
  return BY_SLUG.get(slug);
}

export function firstValueLessonsForCourse(courseSlug: string): FirstValueLessonDefinition[] {
  return FIRST_VALUE_LESSON_CATALOG.filter((row) => row.courseSlug === courseSlug);
}

/** Opções derivadas de módulo/curso: aulas do catálogo presentes no pedido, sem duplicar definições. */
export function firstValueOptionsFromPurchaseLessons(lessonSlugs: string[]): FirstValueLessonDefinition[] {
  const unique = [...new Set(lessonSlugs)];
  return unique
    .map((slug) => BY_SLUG.get(slug))
    .filter((row): row is FirstValueLessonDefinition => Boolean(row))
    .sort((a, b) => a.firstValueRank - b.firstValueRank || a.position - b.position);
}
